a = 10
b = 3

# ARITHMATIC OPERATORS
print( a + b)
print( a - b)
print( a * b)
print( a / b) # always return float
print( a // b) # rounds down to integer
print( a % b) # returns the reminder
print( a ** b) # raises to a power

# Comparison Operator
print( a == b)
print( a != b)
print( a > b)
print( a >= b)
print( a < b)
print( a <= b)

a += 4
print(a)
